#!/usr/bin/env node
/*
 * Generate the static Unicode tables used by the C core.
 *
 * The reference is fuzzysort 4.0.2 (commit ac4d42ec894a2125d78802ec9b5e74e43518d0fc)
 * running on Node 24.x / Unicode 17.  fuzzysort does not use generic NFKD;
 * it remaps one UTF-16 code unit at a time and only keeps an NFKD result when
 * that result is exactly one UTF-16 code unit.  The tables below mirror that
 * behavior exactly.
 *
 * Run from the project root:
 *   node tools/gen_tables.mjs
 */

import { writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url)
const outC = new URL('src/tables.c', root)
const outH = new URL('src/tables.h', root)

// fuzzysort.js:1461-1463 (decoded values, not source text)
const remapFrom = '\\"`‘’‚‛“”„‟«»‹›‐–—−⁄∕…øØłŁđĐðÐıħĦŧŦ'
const remapTo   = "/''''''''''''''----//.oOlLdDdDihHtT"
if(remapFrom.length !== remapTo.length) throw new Error('remap table length mismatch')
const remappings = new Map()
for(let i = 0; i < remapFrom.length; i++) remappings.set(remapFrom[i], remapTo[i])

function remapCharacter(char) {
  let r = remappings.get(char)
  if(r !== undefined) return r
  if(char.charCodeAt(0) < 128) return char
  r = char.normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
  return r.length === 1 ? r : char
}

// 1. BMP remap exceptions.  Surrogate code units are remapped individually
// by fuzzysort's regex and are unchanged, exactly like lone surrogates.
const remap = []
for(let cu = 0; cu <= 0xffff; cu++) {
  const ch = String.fromCharCode(cu)
  const result = remapCharacter(ch)
  if(result !== ch) {
    if(result.length !== 1) throw new Error(`remap result is not one code unit: U+${cu.toString(16)}`)
    remap.push([cu, result.charCodeAt(0)])
  }
}

// 2. Lowercase exceptions.  toLowerCase() operates on code points; store the
// UTF-16 replacement sequence (at most 2 units in Unicode 17).
const lower = []
let maxLowerUnits = 0
for(let cp = 0; cp <= 0x10ffff; cp++) {
  if(cp >= 0xd800 && cp <= 0xdfff) continue
  const ch = String.fromCodePoint(cp)
  const lo = ch.toLowerCase()
  if(lo === ch) continue
  const units = Array.from({length: lo.length}, (_, i) => lo.charCodeAt(i))
  if(units.length > 2) throw new Error(`lowercase expansion too large: U+${cp.toString(16)}`)
  maxLowerUnits = Math.max(maxLowerUnits, units.length)
  lower.push([cp, units])
}
if(maxLowerUnits > 2) throw new Error('unexpected lowercase expansion')

function rangesFor(test) {
  const ranges = []
  let start = -1
  for(let cp = 0; cp <= 0x10ffff; cp++) {
    if(cp >= 0xd800 && cp <= 0xdfff) {
      if(start !== -1) { ranges.push([start, cp - 1]); start = -1 }
      continue
    }
    const yes = test(String.fromCodePoint(cp))
    if(yes && start === -1) start = cp
    else if(!yes && start !== -1) { ranges.push([start, cp - 1]); start = -1 }
  }
  if(start !== -1) ranges.push([start, 0x10ffff])
  return ranges
}

const casedRanges = rangesFor(ch => /^\p{Cased}$/u.test(ch))
const caseIgnorableRanges = rangesFor(ch => /^\p{Case_Ignorable}$/u.test(ch))
const spaceRanges = rangesFor(ch => /^\s$/u.test(ch))

function hex(n, width) { return '0x' + n.toString(16).toUpperCase().padStart(width, '0') }

let c = `/*
 * Generated by tools/gen_tables.mjs.  Do not edit by hand.
 *
 * Source of truth: fuzzysort 4.0.2, commit ac4d42ec894a2125d78802ec9b5e74e43518d0fc,
 * running on Node 24.x (Unicode 17).
 */

#include "tables.h"
#include <stddef.h>

`

c += `static const FuzzyRemapEntry remap_bmp[] = {\n`
for(const [key, value] of remap) c += `  { ${hex(key, 4)}, ${hex(value, 4)} },\n`
c += `};\n\n`

c += `static const FuzzyLowerEntry lower_entries[] = {\n`
for(const [cp, units] of lower) {
  c += `  { ${hex(cp, 6)}, { ${hex(units[0], 4)}, ${hex(units[1] ?? 0, 4)} }, ${units.length} },\n`
}
c += `};\n\n`

function emitRanges(name, ranges) {
  let s = `static const FuzzyRange ${name}[] = {\n`
  for(const [lo, hi] of ranges) s += `  { ${hex(lo, 6)}, ${hex(hi, 6)} },\n`
  s += `};\n\n`
  return s
}
c += emitRanges('cased_ranges', casedRanges)
c += emitRanges('case_ignorable_ranges', caseIgnorableRanges)
c += emitRanges('space_ranges', spaceRanges)

c += `#define REMAP_BMP_COUNT ((int)(sizeof(remap_bmp) / sizeof(remap_bmp[0])))
#define LOWER_COUNT     ((int)(sizeof(lower_entries) / sizeof(lower_entries[0])))
#define CASED_COUNT     ((int)(sizeof(cased_ranges) / sizeof(cased_ranges[0])))
#define IGNORABLE_COUNT ((int)(sizeof(case_ignorable_ranges) / sizeof(case_ignorable_ranges[0])))
#define SPACE_COUNT     ((int)(sizeof(space_ranges) / sizeof(space_ranges[0])))

uint16_t fuzzy_remap_bmp_lookup(uint16_t unit) {
  int lo = 0, hi = REMAP_BMP_COUNT - 1;
  while(lo <= hi) {
    int mid = (lo + hi) >> 1;
    if(remap_bmp[mid].key < unit) lo = mid + 1;
    else if(remap_bmp[mid].key > unit) hi = mid - 1;
    else return remap_bmp[mid].value;
  }
  return unit;
}

bool fuzzy_lower_lookup(uint32_t cp, uint16_t out[2], int *out_len) {
  int lo = 0, hi = LOWER_COUNT - 1;
  while(lo <= hi) {
    int mid = (lo + hi) >> 1;
    if(lower_entries[mid].cp < cp) lo = mid + 1;
    else if(lower_entries[mid].cp > cp) hi = mid - 1;
    else {
      out[0] = lower_entries[mid].out[0];
      out[1] = lower_entries[mid].out[1];
      *out_len = lower_entries[mid].n;
      return true;
    }
  }
  return false;
}

static bool in_ranges(const FuzzyRange *ranges, int count, uint32_t cp) {
  int lo = 0, hi = count - 1;
  while(lo <= hi) {
    int mid = (lo + hi) >> 1;
    if(cp < ranges[mid].lo) hi = mid - 1;
    else if(cp > ranges[mid].hi) lo = mid + 1;
    else return true;
  }
  return false;
}

bool fuzzy_is_cased(uint32_t cp) {
  return in_ranges(cased_ranges, CASED_COUNT, cp);
}

bool fuzzy_is_case_ignorable(uint32_t cp) {
  return in_ranges(case_ignorable_ranges, IGNORABLE_COUNT, cp);
}

bool fuzzy_is_js_space_cp(uint32_t cp) {
  return in_ranges(space_ranges, SPACE_COUNT, cp);
}
`

let h = `/*
 * Generated by tools/gen_tables.mjs.  Do not edit by hand.
 */
#ifndef FUZZY_TABLES_H
#define FUZZY_TABLES_H

#include <stdbool.h>
#include <stdint.h>

typedef struct {
  uint16_t key;
  uint16_t value;
} FuzzyRemapEntry;

typedef struct {
  uint32_t cp;
  uint16_t out[2];
  uint8_t n;
} FuzzyLowerEntry;

typedef struct {
  uint32_t lo;
  uint32_t hi;
} FuzzyRange;

uint16_t fuzzy_remap_bmp_lookup(uint16_t unit);
bool fuzzy_lower_lookup(uint32_t cp, uint16_t out[2], int *out_len);
bool fuzzy_is_cased(uint32_t cp);
bool fuzzy_is_case_ignorable(uint32_t cp);
bool fuzzy_is_js_space_cp(uint32_t cp);

#endif
`

writeFileSync(outC, c)
writeFileSync(outH, h)

console.log(`remap exceptions: ${remap.length}`)
console.log(`lowercase exceptions: ${lower.length}`)
console.log(`ranges: cased=${casedRanges.length}, case-ignorable=${caseIgnorableRanges.length}, space=${spaceRanges.length}`)
console.log(`wrote ${outC.pathname}`)
console.log(`wrote ${outH.pathname}`)
